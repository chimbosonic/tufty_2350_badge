#!/usr/bin/env python3
"""Convert a fixed-width BDF font (e.g. Spleen) to a C header.

Only printable ASCII (32..126) is emitted. Each glyph is stored row-major,
one row per ceil(width/8) bytes, MSB = leftmost pixel.

    tools/bdf2c.py tufty/third_party/spleen/spleen-8x16.bdf font_8x16 > tufty/fonts/font_8x16.h
"""
import sys

FIRST, LAST = 32, 126


def parse(path):
    width = height = None
    glyphs = {}
    enc = None
    rows = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            key = parts[0]
            if key == "FONTBOUNDINGBOX":
                width, height = int(parts[1]), int(parts[2])
            elif key == "ENCODING":
                enc = int(parts[1])
            elif key == "BITMAP":
                rows = []
            elif key == "ENDCHAR":
                if enc is not None and FIRST <= enc <= LAST:
                    glyphs[enc] = rows
                enc, rows = None, None
            elif rows is not None:
                rows.append(int(key, 16))
    if width is None:
        raise SystemExit(f"{path}: no FONTBOUNDINGBOX")
    return width, height, glyphs


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    path, name = sys.argv[1], sys.argv[2]
    width, height, glyphs = parse(path)
    stride = (width + 7) // 8
    out = sys.stdout
    out.write(f"// Generated by tools/bdf2c.py from {path.split('/')[-1]} - do not edit.\n")
    out.write("// Spleen font: Copyright (c) 2018-2026, Frederic Cambus. BSD-2-Clause, see third_party/spleen/LICENSE.\n")
    out.write("#pragma once\n#include \"gfx.h\"\n\n")
    out.write(f"static const uint8_t {name}_data[] = {{\n")
    for code in range(FIRST, LAST + 1):
        rows = glyphs.get(code, [0] * height)
        rows = (rows + [0] * height)[:height]
        data = []
        for r in rows:
            data.extend(r.to_bytes(stride, "big"))
        ch = chr(code)
        label = "\\\\" if ch == "\\" else ch
        out.write(f"    /* '{label}' */ " + ", ".join(f"0x{b:02x}" for b in data) + ",\n")
    out.write("};\n\n")
    out.write(f"static const gfx_font_t {name} = {{ {width}, {height}, {stride}, {FIRST}, {LAST}, {name}_data }};\n")


if __name__ == "__main__":
    main()
